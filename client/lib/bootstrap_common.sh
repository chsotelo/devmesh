# shellcheck shell=bash
# Shared enrollment steps for Linux machines and Termux. Expects DM_* from the bootstrap.

# shellcheck source=trust_common.sh
source "${BASH_SOURCE[0]%/*}/trust_common.sh"
# shellcheck source=tui_target.sh
source "${BASH_SOURCE[0]%/*}/tui_target.sh"

bs_log() { printf '\033[1m==>\033[0m %s\n' "$*" >&2; }
bs_die() {
  printf '\033[31merror:\033[0m %s\n' "$*" >&2
  exit 1
}

# bs_install_tui SRC_BIN_DIR DEST_BIN_DIR: the dm-tui binary of this device's OS/arch, when the
# bundle carries one (enrollment bundles do not: "dm update" brings it).
bs_install_tui() {
  local target
  target=$(tui_target) || return 0
  [[ -f $1/dm-tui-$target ]] || return 0
  install -d "$2"
  install -m 0755 "$1/dm-tui-$target" "$2/dm-tui-$target"
}

bs_require_env() {
  local v
  for v in DM_NAME DM_KIND DM_IP DM_HUB_HOST DM_HUB_IP DM_HUB_SSH_PORT DM_WG_PORT DM_WG_IFACE DM_SUBNET_PREFIX \
    DM_HUB_WG_PUB DM_HUB_HOST_KEY DM_VERSION DM_ENROLL_KEY_FILE DM_DIST_DIR; do
    [[ -n ${!v:-} ]] || bs_die "bootstrap is missing $v"
  done
}

# bs_ssh_keygen FILE COMMENT [AS_USER] — create an ed25519 key once.
bs_ssh_keygen() {
  local file=$1 comment=$2 as_user=${3:-}
  [[ -s $file ]] && return 0
  if [[ -n $as_user ]]; then
    sudo -u "$as_user" ssh-keygen -q -t ed25519 -N '' -C "$comment" -f "$file"
  else
    ssh-keygen -q -t ed25519 -N '' -C "$comment" -f "$file"
  fi
}

bs_pub_bare() {
  local type key
  read -r type key _ <"$1"
  printf '%s %s\n' "$type" "$key"
}

# bs_wg_key FILE — WireGuard private key, generated once, never leaves the device.
bs_wg_key() {
  [[ -s $1 ]] || (umask 077 && wg genkey >"$1")
  chmod 0600 "$1"
}

# bs_hub_curl ARGS... - curl against the hub over HTTPS. With DM_HUB_PIN (IP mode, no CA
# vouches for the hub) the connection is pinned to the hub's public key; -k only skips
# CA validation, curl still enforces the pin.
bs_hub_curl() {
  if [[ -n ${DM_HUB_PIN:-} ]]; then
    curl -fsSL --pinnedpubkey "sha256//$DM_HUB_PIN" -k "$@"
  else
    curl -fsSL "$@"
  fi
}

# bs_hostport HOST PORT - "host:port", IPv6 literals in brackets (WireGuard Endpoint).
bs_hostport() {
  if [[ $1 == *:* ]]; then printf '[%s]:%s\n' "$1" "$2"; else printf '%s:%s\n' "$1" "$2"; fi
}

bs_hub_known_hosts() {
  # shellcheck disable=SC2153 # DM_HUB_IP is exported by the join script, not a typo of DM_HUB_PIN
  printf '%s,%s %s\n' "$DM_HUB_HOST" "$DM_HUB_IP" "$DM_HUB_HOST_KEY"
}

# bs_enroll KNOWN_HOSTS < fields — hand public keys (and the detected kind) to the hub with
# the throwaway key. The hub answers "OK <name> <ip> <port> <color>": port and color are
# assigned there (machines only), so they are taken from the reply.
bs_enroll() {
  local known=$1 reply _ip
  chmod 0600 "$DM_ENROLL_KEY_FILE"
  [[ -n ${DM_ENROLL_PASS:-} ]] || bs_die "missing enrollment secret: paste the whole command printed by 'invite'"
  ssh-keygen -q -p -P "$DM_ENROLL_PASS" -N '' -f "$DM_ENROLL_KEY_FILE" >/dev/null 2>&1 ||
    bs_die "wrong enrollment secret"
  reply=$({
    printf 'kind %s\n' "$DM_KIND"
    cat
  } | ssh -i "$DM_ENROLL_KEY_FILE" -o IdentitiesOnly=yes -o BatchMode=yes \
    -o UserKnownHostsFile="$known" -o StrictHostKeyChecking=yes -o ConnectTimeout=15 \
    -o HostKeyAlias="$DM_HUB_HOST" -o IgnoreUnknown=WarnWeakCrypto -o WarnWeakCrypto=no-pq-kex \
    -p "${DM_HUB_SSH_PORT:-2222}" "enroll@$DM_HUB_HOST" enroll) || bs_die "hub rejected the enrollment (expired or already used code?)"
  [[ $reply == "OK $DM_NAME "* ]] || bs_die "unexpected hub reply: $reply"
  read -r _ _ _ip DM_PORT DM_COLOR <<<"$reply"
  export DM_PORT DM_COLOR
  bs_log "hub accepted $DM_NAME"
}

# bs_wg_conf PRIVATE_KEY [MTU] — client config; only the devmesh subnet is routed.
bs_wg_conf() {
  local key=$1 mtu=${2:-}
  printf '[Interface]\nPrivateKey = %s\nAddress = %s/24\n' "$key" "$DM_IP"
  [[ -n $mtu ]] && printf 'MTU = %s\n' "$mtu"
  printf '\n[Peer]\nPublicKey = %s\nEndpoint = %s\nAllowedIPs = %s.0/24\nPersistentKeepalive = 25\n' \
    "$DM_HUB_WG_PUB" "$(bs_hostport "$DM_HUB_HOST" "$DM_WG_PORT")" "$DM_SUBNET_PREFIX"
}

# Minimal ssh_config so "dm refresh" can reach hub-admin before the full config exists.
bs_ssh_bootstrap_config() {
  cat <<EOF
# Generated by devmesh bootstrap; replaced by "dm refresh".
Host hub-admin
  HostName $DM_HUB_HOST
  Port ${DM_HUB_SSH_PORT:-2222}
  User dmadmin
  IgnoreUnknown WarnWeakCrypto
  WarnWeakCrypto no-pq-kex
  HostKeyAlias $DM_HUB_HOST
  IdentityFile ~/.ssh/id_devmesh
  IdentitiesOnly yes
  UserKnownHostsFile ~/.ssh/devmesh_known_hosts
  StrictHostKeyChecking yes
EOF
}

# bs_ensure_line FILE LINE — append LINE once (idempotent rc/config edits).
bs_ensure_line() {
  local file=$1 line=$2
  [[ -f $file ]] && grep -qxF "$line" "$file" && return 0
  printf '%s\n' "$line" >>"$file"
}

# bs_ensure_include SSH_CONFIG — "Include config.d/devmesh" must be the first line so the
# devmesh hosts take precedence over later wildcard blocks.
bs_ensure_include() {
  local cfg=$1 line="Include config.d/devmesh" tmp
  mkdir -p "${cfg%/*}/config.d"
  [[ -f $cfg ]] || : >"$cfg"
  grep -qxF "$line" "$cfg" && return 0
  tmp=$(mktemp)
  {
    printf '%s\n' "$line"
    cat "$cfg"
  } >"$tmp"
  cat "$tmp" >"$cfg"
  rm -f "$tmp"
  chmod 0600 "$cfg"
}

# bs_store_epoch ALLOWED FILE — keep the delivered "epoch <serial> <hash> <signer> <sig>" when an
# approver in ALLOWED really signed it.
bs_store_epoch() {
  local kind serial hash sig
  read -r kind serial hash _ sig <"$2" || return 0
  [[ $kind == epoch && $serial =~ ^[0-9]{1,9}$ && $hash =~ ^[0-9a-f]+$ ]] || return 0
  tr_verify "$1" "$sig" "$(tr_msg epoch "$serial" "$hash")" >/dev/null || return 0
  printf '%s %s\n' "$serial" "$hash" >"$(tr_epoch_file "$1")"
}

# bs_trust_setup ALLOWED CLIENT_PUB — local allowed_signers (OSS-20). The owner device trusts
# its own key; any other device takes the approvers the join script delivered (owner entries on
# first use, the rest only with a valid signature chain). Sets DM_TRUST_MODE for node.conf.
bs_trust_setup() {
  local allowed=$1 pub=$2
  DM_TRUST_MODE=open
  if [[ ${DM_OWNER:-0} == 1 ]]; then
    tr_allowed_line "$DM_NAME" "$(bs_pub_bare "$pub")" >"$allowed"
  elif [[ -s ${DM_SIGNERS_FILE:-/nonexistent} && ! -s $allowed ]]; then
    tr_import_signers "$DM_SIGNERS_FILE" "$allowed" || bs_log "no usable approver delivered; trust stays open"
  fi
  # Delivered epoch (trusted on first use like the approvers): rollbacks below it are refused.
  if [[ -s $allowed && ! -e $(tr_epoch_file "$allowed") && -s ${DM_EPOCH_FILE:-/nonexistent} ]]; then
    bs_store_epoch "$allowed" "$DM_EPOCH_FILE"
  fi
  [[ -s $allowed ]] && DM_TRUST_MODE=signed
  export DM_TRUST_MODE
  return 0
}

# bs_fp FILE — SHA256 fingerprint of a public key file.
bs_fp() { ssh-keygen -lf "$1" | awk '{print $2}'; }

# bs_approve_hint CLIENT_PUB [HOST_PUB] — what to compare when an approver asks about this device.
bs_approve_hint() {
  [[ ${DM_OWNER:-0} != 1 ]] || return 0
  [[ ${DM_TRUST_MODE:-open} == signed ]] || return 0
  printf 'Approve on an approver device: dm approve %s  (check: client %s%s)\n' "$DM_NAME" "$(bs_fp "$1")" \
    "${2:+, host $(bs_fp "$2")}"
}

bs_node_conf() {
  cat <<EOF
# devmesh node identity (written at enrollment)
DM_NAME=$DM_NAME
DM_KIND=$DM_KIND
DM_IP=$DM_IP
DM_PORT=${DM_PORT:--}
DM_COLOR=${DM_COLOR:--}
DM_HUB_HOST=$DM_HUB_HOST
DM_HUB_IP=$DM_HUB_IP
DM_HUB_SSH_PORT=${DM_HUB_SSH_PORT:-2222}
DM_HUB_WG_PUB=$DM_HUB_WG_PUB
DM_WG_IFACE=$DM_WG_IFACE
DM_WG_PORT=$DM_WG_PORT
DM_WATCH_TOPIC=${DM_WATCH_TOPIC:--}
DM_VERSION=$DM_VERSION
DM_ENROLLED=1
DM_TRUST=${DM_TRUST_MODE:-open}
EOF
  # IP mode only: the certificate pin the hub was joined with.
  [[ -z ${DM_HUB_PIN:-} ]] || printf 'DM_HUB_PIN=%s\n' "$DM_HUB_PIN"
  # Linux mesh firewall: extra ports opened with "devmesh-node mesh open".
  [[ -z ${DM_MESH_OPEN:-} ]] || printf 'DM_MESH_OPEN="%s"\n' "$DM_MESH_OPEN"
  # LANs whose devices reach ssh/mosh directly, "<cidr>@<router MAC>" ("devmesh-node lan trust").
  [[ -z ${DM_LAN_TRUST:-} ]] || printf 'DM_LAN_TRUST="%s"\n' "$DM_LAN_TRUST"
  return 0
}

# Already enrolled as this name? Then re-running only re-applies local config, using the
# tunnel port and color the hub assigned the first time.
bs_already_enrolled() {
  local conf=$1
  # Same name AND same kind: a device re-joining with another role must enroll again.
  [[ -r $conf ]] && grep -qxF "DM_NAME=$DM_NAME" "$conf" && grep -qxF "DM_ENROLLED=1" "$conf" &&
    grep -qxF "DM_KIND=$DM_KIND" "$conf" || return 1
  DM_PORT=$(sed -n 's/^DM_PORT=//p' "$conf")
  DM_COLOR=$(sed -n 's/^DM_COLOR=//p' "$conf")
  # Ports the owner opened on the mesh firewall survive a re-run.
  DM_MESH_OPEN=$(sed -n 's/^DM_MESH_OPEN="\(.*\)"$/\1/p' "$conf")
  [[ $DM_MESH_OPEN =~ ^[a-z0-9/\ -]*$ ]] || DM_MESH_OPEN=""
  DM_LAN_TRUST=$(sed -n 's/^DM_LAN_TRUST="\(.*\)"$/\1/p' "$conf")
  [[ $DM_LAN_TRUST =~ ^[0-9a-f./@:\ ]*$ ]] || DM_LAN_TRUST=""
  export DM_PORT DM_COLOR DM_MESH_OPEN DM_LAN_TRUST
}
