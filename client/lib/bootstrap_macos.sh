# shellcheck shell=bash
# Enrollment of a Mac as a machine: its terminals are shared like a Linux machine's.
# No sudo and nothing listening on any network: a user-level sshd answers on 127.0.0.1
# only, and other devices reach it through the reverse tunnel to the hub. Everything
# runs as the user via launchd agents (sshd, tunnel, key sync, tmux "main").

# shellcheck source=bootstrap_common.sh
source "$DM_DIST_DIR/lib/bootstrap_common.sh"

MX_CONF_DIR=${MX_CONF_DIR:-$HOME/.config/devmesh}
MX_SHARE=${MX_SHARE:-$HOME/.local/share/devmesh}
MX_BIN=${MX_BIN:-}
MX_AGENTS=${MX_AGENTS:-$HOME/Library/LaunchAgents}
MX_SSH_PORT=2223

macos_brew_bin() {
  if [[ -n $MX_BIN ]]; then
    printf '%s\n' "$MX_BIN"
  else
    printf '%s/bin\n' "$(brew --prefix)"
  fi
}

# fzf (pickers), tmux (shared terminals), wireguard-tools (local key generation only),
# coreutils (timeout, used by the hub watcher).
macos_deps() {
  command -v brew >/dev/null || bs_die "Homebrew is required (https://brew.sh)"
  local missing=() tool
  for tool in fzf:fzf tmux:tmux wg:wireguard-tools timeout:coreutils; do
    command -v "${tool%%:*}" >/dev/null || missing+=("${tool#*:}")
  done
  if ((${#missing[@]})); then
    bs_log "installing ${missing[*]} with Homebrew"
    brew install --quiet "${missing[@]}" >/dev/null
  fi
}

macos_keys() {
  install -d -m 0700 "$HOME/.ssh" "$MX_CONF_DIR"
  bs_wg_key "$MX_CONF_DIR/wg.key"
  bs_ssh_keygen "$HOME/.ssh/id_devmesh" "devmesh:$DM_NAME"
  bs_ssh_keygen "$MX_CONF_DIR/tunnel_ed25519" "devmesh-tunnel:$DM_NAME"
  bs_ssh_keygen "$MX_CONF_DIR/ssh_host_ed25519_key" "devmesh-host:$DM_NAME"
  bs_hub_known_hosts >"$HOME/.ssh/devmesh_known_hosts"
  bs_hub_known_hosts >"$MX_CONF_DIR/known_hosts"
  [[ -e $MX_CONF_DIR/clients.pub ]] || install -m 0600 /dev/null "$MX_CONF_DIR/clients.pub"
}

macos_enroll_fields() {
  printf 'wg %s\n' "$(wg pubkey <"$MX_CONF_DIR/wg.key")"
  printf 'client %s\n' "$(bs_pub_bare "$HOME/.ssh/id_devmesh.pub")"
  printf 'tunnel %s\n' "$(bs_pub_bare "$MX_CONF_DIR/tunnel_ed25519.pub")"
  printf 'host %s\n' "$(bs_pub_bare "$MX_CONF_DIR/ssh_host_ed25519_key.pub")"
  printf 'user %s\n' "$(id -un)"
  printf 'os macos\n'
}

macos_install_client() {
  local bin
  bin=$(macos_brew_bin)
  rm -rf "${MX_SHARE:?}/lib" "${MX_SHARE:?}/shell" "${MX_SHARE:?}/hooks" "${MX_SHARE:?}/tmux" "${MX_SHARE:?}/sbin"
  install -d "$MX_SHARE" "$MX_SHARE/sbin" "$bin"
  cp -R "$DM_DIST_DIR/lib" "$DM_DIST_DIR/shell" "$DM_DIST_DIR/hooks" "$DM_DIST_DIR/tmux" "$MX_SHARE/"
  install -m 0755 "$DM_DIST_DIR/bin/dm" "$bin/dm"
  install -m 0755 "$DM_DIST_DIR/sbin/devmesh-node" "$MX_SHARE/sbin/devmesh-node"
  printf '%s\n' "$DM_VERSION" >"$MX_SHARE/VERSION"
  bs_install_tui "$DM_DIST_DIR/bin" "$MX_SHARE/bin"
  local rc line="[ -r $MX_SHARE/shell/devmesh.sh ] && . $MX_SHARE/shell/devmesh.sh"
  # zsh is the macOS default shell; bash only if the user already has a ~/.bashrc.
  for rc in "$HOME/.zshrc" "$HOME/.bashrc"; do
    if [[ -f $rc || $rc == "$HOME/.zshrc" ]]; then
      bs_ensure_line "$rc" "$line"
    fi
  done
  macos_reap_agent
}

# Idle Claude sessions stop by themselves: a user agent every 5 minutes. Installed with the
# client, so "dm update" gives it to machines enrolled before this existed.
macos_reap_agent() {
  local bash5
  bash5="$(macos_brew_bin)/bash"
  install -d -m 0700 "$MX_CONF_DIR/logs"
  install -d "$MX_AGENTS"
  macos_plist net.devmesh.claude-reap '  <key>StartInterval</key><integer>300</integer>' \
    "$bash5" "$(macos_brew_bin)/dm" _claude_reap >"$MX_AGENTS/net.devmesh.claude-reap.plist"
  macos_load_agent net.devmesh.claude-reap || bs_log "could not load net.devmesh.claude-reap"
}

# User-level sshd: localhost only, this user only, keys only (the synced clients.pub).
macos_sshd_config() {
  cat <<EOF
# Generated by devmesh. Runs as $(id -un); reachable only through the devmesh tunnel.
Port $MX_SSH_PORT
ListenAddress 127.0.0.1
HostKey $MX_CONF_DIR/ssh_host_ed25519_key
PidFile $MX_CONF_DIR/sshd.pid
AuthorizedKeysFile $MX_CONF_DIR/clients.pub
AllowUsers $(id -un)
AuthenticationMethods publickey
PasswordAuthentication no
KbdInteractiveAuthentication no
UsePAM no
PermitRootLogin no
PermitUserEnvironment no
X11Forwarding no
ClientAliveInterval 15
ClientAliveCountMax 3
SetEnv PATH=$(macos_brew_bin):/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin
Subsystem sftp /usr/libexec/sftp-server
EOF
}

# macos_plist LABEL EXTRA_XML PROGRAM ARGS... — a launchd agent running as the user.
macos_plist() {
  local label=$1 extra=$2 arg args=""
  shift 2
  for arg in "$@"; do
    args+="    <string>$arg</string>"$'\n'
  done
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array>
$args  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>$(macos_brew_bin):/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    <key>NODE_ETC</key><string>$MX_CONF_DIR</string>
    <key>NODE_STATE</key><string>$MX_CONF_DIR/state</string>
    <key>NODE_SHARE</key><string>$MX_SHARE</string>
  </dict>
  <key>RunAtLoad</key><true/>
$extra
  <key>StandardErrorPath</key><string>$MX_CONF_DIR/logs/$label.log</string>
</dict>
</plist>
EOF
}

macos_load_agent() {
  local label=$1 plist="$MX_AGENTS/$1.plist"
  launchctl bootout "gui/$(id -u)/$label" >/dev/null 2>&1 || true
  launchctl bootstrap "gui/$(id -u)" "$plist" 2>/dev/null || launchctl load -w "$plist"
}

macos_services() {
  local bash5 node keep a
  bash5="$(macos_brew_bin)/bash"
  node="$MX_SHARE/sbin/devmesh-node"
  keep='  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>10</integer>'
  install -d -m 0700 "$MX_CONF_DIR/logs" "$MX_CONF_DIR/state"
  install -d "$MX_AGENTS"
  macos_sshd_config >"$MX_CONF_DIR/sshd_config"
  /usr/sbin/sshd -t -f "$MX_CONF_DIR/sshd_config" || bs_die "sshd rejected the devmesh config"
  macos_plist net.devmesh.sshd "$keep" /usr/sbin/sshd -D -f "$MX_CONF_DIR/sshd_config" >"$MX_AGENTS/net.devmesh.sshd.plist"
  macos_plist net.devmesh.tunnel "$keep" "$bash5" "$node" tunnel >"$MX_AGENTS/net.devmesh.tunnel.plist"
  macos_plist net.devmesh.keys '  <key>StartInterval</key><integer>60</integer>' \
    "$bash5" "$node" keys-sync >"$MX_AGENTS/net.devmesh.keys.plist"
  macos_plist net.devmesh.tmux "$keep" /bin/sh -c \
    "while :; do tmux has-session -t =main 2>/dev/null || tmux new-session -d -s main; sleep 30; done" \
    >"$MX_AGENTS/net.devmesh.tmux.plist"
  for a in sshd tunnel keys tmux; do
    macos_load_agent "net.devmesh.$a"
  done
}

macos_tmux_conf() {
  cat >"$HOME/.tmux.devmesh.conf" <<EOF
# Generated by devmesh for $DM_NAME.
set -g @dm_name "$DM_NAME"
set -g status-style "bg=colour${DM_COLOR:-24},fg=white"
set -g @dm_color "${DM_COLOR:-24}"
source-file $MX_SHARE/tmux/base.conf
EOF
  bs_ensure_line "$HOME/.tmux.conf" "source-file -q ~/.tmux.devmesh.conf"
}

# The tunnel config (holds this Mac's WireGuard private key) stays under ~/.config,
# readable only by the user, ready to import in the WireGuard app. Optional on a Mac:
# its own terminals are reached through the hub; the VPN only speeds up reaching others.
macos_wireguard_conf() {
  local dir="$MX_CONF_DIR/wireguard"
  install -d -m 0700 "$dir"
  (umask 077 && bs_wg_conf "$(cat "$MX_CONF_DIR/wg.key")" >"$dir/devmesh.conf")
  printf '%s\n' "$dir/devmesh.conf"
}

macos_node_conf() {
  bs_node_conf
  printf 'DM_LOCAL_SSH_PORT=%s\n' "$MX_SSH_PORT"
}

bootstrap_main() {
  bs_require_env
  umask 022
  [[ $(uname -s) == Darwin ]] || bs_die "this bootstrap is for macOS"
  ((BASH_VERSINFO[0] >= 4)) || bs_die "run it with Homebrew's bash (brew install bash)"
  macos_deps
  macos_keys
  bs_trust_setup "$MX_CONF_DIR/allowed_signers" "$HOME/.ssh/id_devmesh.pub"
  if bs_already_enrolled "$MX_CONF_DIR/node.conf"; then
    bs_log "already enrolled as $DM_NAME; re-applying local config"
  else
    bs_enroll "$HOME/.ssh/devmesh_known_hosts" < <(macos_enroll_fields)
    macos_node_conf >"$MX_CONF_DIR/node.conf"
  fi
  macos_node_conf >"$MX_CONF_DIR/node.conf"
  macos_install_client
  bs_ensure_include "$HOME/.ssh/config"
  bs_ssh_bootstrap_config >"$HOME/.ssh/config.d/devmesh"
  macos_tmux_conf
  macos_services
  local conf
  conf=$(macos_wireguard_conf)
  "$(macos_brew_bin)/dm" refresh || bs_log "dm refresh failed; run it again later"
  printf '\n\033[32m%s ✓\033[0m  machine · tunnel :%s · color %s · new terminals start in tmux\n' \
    "$DM_NAME" "$DM_PORT" "$DM_COLOR"
  bs_approve_hint "$HOME/.ssh/id_devmesh.pub" "$MX_CONF_DIR/ssh_host_ed25519_key.pub"
  printf 'Optional VPN: WireGuard app → Import tunnel(s) from file → %s\n' "$conf"
}
