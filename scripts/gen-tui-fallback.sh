#!/usr/bin/env bash
# Regenerates tui/internal/i18n/fallback.go: the English text of every catalog key the Go
# panel uses (listed in tui/internal/i18n/keys.go), read from client/lib/i18n/en.sh.
# Usage: scripts/gen-tui-fallback.sh
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# shellcheck source=../client/lib/i18n/en.sh
source "$root/client/lib/i18n/en.sh"
out=$root/tui/internal/i18n/fallback.go
{
  printf '// Code generated by scripts/gen-tui-fallback.sh from client/lib/i18n/en.sh; DO NOT EDIT.\n\n'
  printf 'package i18n\n\n'
  printf '// english is the embedded fallback, used when "dm _i18n" cannot be read.\n'
  printf 'var english = map[string]string{\n'
  grep -o '"M_[A-Z0-9_]*"' "$root/tui/internal/i18n/keys.go" | tr -d '"' | sort -u | while read -r key; do
    value=${!key}
    value=${value//\\/\\\\}
    value=${value//\"/\\\"}
    printf '\t"%s": "%s",\n' "$key" "$value"
  done
  printf '}\n'
} >"$out"
gofmt -w "$out"
