# shellcheck shell=bash
# install-hub: packages, files, hub keys, restricted users, sudoers and sshd.

readonly HUB_USERS=(tunnel enroll dmadmin)

# --no-install-recommends everywhere: on Ubuntu 20.04, wireguard-tools alone would pull
# kernel images, firmware and initramfs-tools onto the production host (30 pkgs vs 3).
step_packages() {
  if ((IH_CONTAINER)); then
    ih_log "container: packages come from the image"
    return 0
  fi
  ih_log "packages"
  DEBIAN_FRONTEND=noninteractive apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends wireguard-tools curl fail2ban vnstat iproute2 >/dev/null
  # Built-in or module: creating a throwaway interface is the reliable check.
  if ip link add dm-wgtest type wireguard 2>/dev/null; then
    ip link del dm-wgtest
  else
    modprobe wireguard 2>/dev/null || ih_die "this kernel has no WireGuard support"
  fi
}

step_files() {
  ih_log "devmesh $(cat "$IH_SRC/VERSION") files"
  install -d -m 0755 "$DEVMESH_LIB" "$DEVMESH_SHARE" "$DEVMESH_SHARE/templates"
  install -d -m 0755 "$DEVMESH_ETC" "$DEVMESH_SSH_KEYS" "$DEVMESH_STATE"
  install -d -m 0700 "$DEVMESH_INVITES" "$DEVMESH_BACKUP_DIR"
  install -d -m 0755 "$DEVMESH_WEBROOT" "$DEVMESH_WEBROOT/j" "$DEVMESH_WEBROOT/acme"
  install -m 0644 "$IH_SRC"/server/lib/*.sh "$DEVMESH_LIB/"
  install -m 0755 "$IH_SRC/server/sbin/devmesh" "$IH_SRC/server/sbin/devmesh-fw" \
    "$IH_SRC/server/sbin/devmesh-keys-out" "$DEVMESH_SBIN/"
  install -m 0644 "$IH_SRC"/server/templates/*.tpl "$DEVMESH_SHARE/templates/"
  rm -rf "$DEVMESH_SHARE/client"
  cp -R "$IH_SRC/client" "$DEVMESH_SHARE/client"
  # Signed client bundle built and signed on an approver's machine by "make hub".
  rm -rf "$DEVMESH_SHARE/dist"
  if [[ -r $IH_SRC/dist/dist.tgz && -r $IH_SRC/dist/dist.sig ]]; then
    install -d -m 0755 "$DEVMESH_SHARE/dist"
    install -m 0644 "$IH_SRC/dist/dist.tgz" "$IH_SRC/dist/dist.sig" "$DEVMESH_SHARE/dist/"
  fi
  chmod -R u=rwX,go=rX "$DEVMESH_SHARE"
  install -m 0644 "$IH_SRC/VERSION" "$DEVMESH_SHARE/VERSION"
}

step_hub_keys() {
  if [[ ! -s $DEVMESH_HUB_KEY ]]; then
    ih_log "generating hub WireGuard key"
    (umask 077 && wg genkey >"$DEVMESH_HUB_KEY")
  fi
  chmod 0600 "$DEVMESH_HUB_KEY"
  # devmesh's own sshd host key (never the system one).
  [[ -s $DEVMESH_HOST_KEY_PUB ]] ||
    ssh-keygen -q -t ed25519 -N '' -C "devmesh-hub" -f "${DEVMESH_HOST_KEY_PUB%.pub}"
  chmod 0600 "${DEVMESH_HOST_KEY_PUB%.pub}"
  [[ -e $DEVMESH_REGISTRY ]] || install -m 0600 /dev/null "$DEVMESH_REGISTRY"
  [[ -e $DEVMESH_CLIENTS_PUB ]] || install -m 0644 /dev/null "$DEVMESH_CLIENTS_PUB"
}

# Restricted accounts. Password field "*" = no password login but not "locked", so
# public-key auth works with or without PAM. Every key line carries a forced command.
step_users() {
  ih_log "restricted users: ${HUB_USERS[*]}"
  local u
  for u in "${HUB_USERS[@]}"; do
    if ! id "$u" >/dev/null 2>&1; then
      useradd --system --create-home --home-dir "$DEVMESH_STATE/home/$u" --shell /bin/sh "$u"
    fi
    usermod -p '*' -s /bin/sh "$u"
    [[ -e $DEVMESH_SSH_KEYS/$u.keys ]] || install -m 0644 /dev/null "$DEVMESH_SSH_KEYS/$u.keys"
  done
}

step_sudoers() {
  local file=$IH_SUDOERS_DIR/devmesh tmp
  tmp=$(mktemp)
  cat >"$tmp" <<EOF
# Generated by devmesh install-hub. Forced commands of the enroll/dmadmin keys.
Defaults!$DEVMESH_SBIN/devmesh env_keep += "SSH_ORIGINAL_COMMAND SSH_CONNECTION"
enroll  ALL=(root) NOPASSWD: $DEVMESH_SBIN/devmesh _enroll *
dmadmin ALL=(root) NOPASSWD: $DEVMESH_SBIN/devmesh _ssh *
EOF
  visudo -cqf "$tmp" || {
    rm -f "$tmp"
    ih_die "generated sudoers is invalid"
  }
  install -m 0440 "$tmp" "$file"
  rm -f "$tmp"
}

# devmesh runs its OWN sshd (devmesh-sshd.service, port HUB_SSH_PORT) with its own config,
# host key and limits. The system sshd of a production host is never modified, and the
# devmesh port does not share brute-force load, MaxStartups or fail2ban bans with port 22.
devmesh_sshd_config() {
  cat <<EOF
# Generated by devmesh install-hub. Only the restricted devmesh accounts, keys only.
Port $HUB_SSH_PORT
HostKey ${DEVMESH_HOST_KEY_PUB%.pub}
PidFile /run/devmesh-sshd.pid
AllowUsers ${HUB_USERS[*]}
AuthenticationMethods publickey
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
ChallengeResponseAuthentication no
PermitRootLogin no
PermitEmptyPasswords no
PermitUserEnvironment no
UsePAM no
MaxAuthTries 3
LoginGraceTime 20
MaxStartups 10:30:60
# Drop dead tunnels in ~45 s so a machine can re-bind its reverse port.
ClientAliveInterval 15
ClientAliveCountMax 3
PermitTTY no
X11Forwarding no
AllowAgentForwarding no
AllowStreamLocalForwarding no
PermitTunnel no
GatewayPorts no
AllowTcpForwarding no
LogLevel VERBOSE
SyslogFacility AUTH
Match User tunnel
    AuthorizedKeysFile $DEVMESH_SSH_KEYS/tunnel.keys
    AllowTcpForwarding yes
Match User enroll,dmadmin
    AuthorizedKeysFile $DEVMESH_SSH_KEYS/%u.keys
EOF
}

step_sshd() {
  ih_log "devmesh-sshd on port $HUB_SSH_PORT (system sshd untouched)"
  local conf="$DEVMESH_ETC/sshd_config" tmp
  # Older devmesh versions used a drop-in in the system sshd: remove it if present.
  if ! ((IH_CONTAINER)) && [[ -e /etc/ssh/sshd_config.d/50-devmesh.conf ]]; then
    rm -f /etc/ssh/sshd_config.d/50-devmesh.conf
    sshd -t && { systemctl reload ssh 2>/dev/null || systemctl reload sshd; }
  fi
  tmp=$(mktemp)
  devmesh_sshd_config >"$tmp"
  install -d -m 0755 "$IH_SSHD_RUNDIR"
  "$IH_SSHD" -t -f "$tmp" || {
    rm -f "$tmp"
    ih_die "devmesh sshd config rejected by sshd -t"
  }
  install -m 0644 "$tmp" "$conf"
  rm -f "$tmp"
  if ((IH_CONTAINER)); then
    ih_log "container: sshd is started by the entrypoint"
    return 0
  fi
  install -m 0644 "$IH_SRC/server/systemd/devmesh-sshd.service" /etc/systemd/system/devmesh-sshd.service
  systemctl daemon-reload
  systemctl enable devmesh-sshd.service >/dev/null
  systemctl restart devmesh-sshd.service
  if command -v ufw >/dev/null && ufw status | grep -q '^Status: active'; then
    ufw allow "$HUB_SSH_PORT/tcp" comment devmesh-sshd >/dev/null
  fi
}

# fail2ban: bans also cover the devmesh port, and traffic over the VPN never counts.
step_fail2ban() {
  if ((IH_CONTAINER)); then
    ih_log "container: fail2ban is not run here; run it on the host and ban ports ssh,$HUB_SSH_PORT (never $SUBNET_PREFIX.0/24)"
    return 0
  fi
  command -v fail2ban-client >/dev/null || return 0
  ih_log "fail2ban: ban ports ssh,$HUB_SSH_PORT; never ban $SUBNET_PREFIX.0/24"
  local ignore _
  if ! systemctl is-active --quiet fail2ban; then
    systemctl enable --now fail2ban >/dev/null 2>&1 || ih_die "fail2ban is installed but cannot start"
  fi
  for _ in $(seq 1 20); do
    fail2ban-client ping >/dev/null 2>&1 && break
    sleep 0.5
  done
  # Keep whatever the host already ignores (e.g. admin IPs), then add the VPN subnet.
  ignore=$({ fail2ban-client get sshd ignoreip 2>/dev/null || true; } |
    { grep -Eo '[0-9a-f.:]+/[0-9]+|[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+|::1' || true; } | sort -u | tr '\n' ' ')
  [[ $ignore == *127.0.0.1* ]] || ignore+=" 127.0.0.1/8 ::1"
  cat >/etc/fail2ban/jail.d/devmesh.conf <<EOF
# Generated by devmesh install-hub.
[sshd]
port = ssh,$HUB_SSH_PORT
ignoreip = $ignore $SUBNET_PREFIX.0/24
EOF
  fail2ban-client -t >/dev/null 2>&1 || {
    rm -f /etc/fail2ban/jail.d/devmesh.conf
    ih_die "fail2ban rejected the devmesh jail override; removed it"
  }
  systemctl reload fail2ban 2>/dev/null || systemctl restart fail2ban
}
